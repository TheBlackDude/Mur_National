#!/usr/bin/env node
// Regenerates functions/src/prefectures.ts from web/src/data/prefectures.json so the callables stamp the same
// region on a contribution as the Wall filters by. Run after editing the JSON:  node scripts/sync-prefectures.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('..', import.meta.url)
const prefs = JSON.parse(readFileSync(new URL('web/src/data/prefectures.json', root), 'utf8'))
const lines = prefs.map((p) => `  '${p.code}': ${JSON.stringify(p.region)},`)
writeFileSync(new URL('functions/src/prefectures.ts', root), `// Generated by scripts/sync-prefectures.mjs from web/src/data/prefectures.json — do not edit by hand.
/** Administrative region of every prefecture code (Conakry communes are CKY-*). */
export const REGION_OF: Record<string, string> = {
${lines.join('\n')}
}
export const PREFECTURE_CODES = new Set(Object.keys(REGION_OF))
`)
console.log(`functions/src/prefectures.ts: ${prefs.length} codes`)
